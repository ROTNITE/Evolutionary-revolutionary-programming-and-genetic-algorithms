#!/usr/bin/env python3
"""ЛР №2: генетический алгоритм для рюкзака с обязательными и конфликтующими предметами.

Демонстрационный V=3 (индивидуальный V по N,Q не известен).
Честное сравнение по числу оценок, повторяемые серии запусков.
Только NumPy/Matplotlib для ГПСЧ, статистики и визуализаций.
"""
from __future__ import annotations
import argparse
import csv
import json
from dataclasses import dataclass
from pathlib import Path
import time

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

DATA_SEED = 2026101802
DEFAULT_SEED_BASE = 2026102000


@dataclass(frozen=True)
class Problem:
    weight: np.ndarray
    value: np.ndarray
    mandatory: tuple[int,...]
    conflicts: tuple[tuple[int,int], ...]
    capacity: int

    @property
    def n(self) -> int: return len(self.weight)


def create_problem(seed: int = DATA_SEED) -> Problem:
    rng = np.random.default_rng(seed)
    n = 40
    weight = rng.integers(3, 21, size=n, dtype=np.int64)
    value = 3 * weight + rng.integers(5, 46, size=n, dtype=np.int64)
    mandatory = (0,1,2)
    # Не допускаем конфликтов между обязательными предметами.
    candidates = [(i,j) for i in range(n) for j in range(i+1,n)
                  if not (i in mandatory and j in mandatory)]
    indices = rng.choice(len(candidates), size=24, replace=False)
    conflicts = tuple(sorted(candidates[int(i)] for i in indices))
    capacity = int(sum(weight[list(mandatory)]) + 87)
    return Problem(weight, value, mandatory, conflicts, capacity)


def save_problem(p: Problem, out_dir: Path) -> None:
    with (out_dir/'items.csv').open('w',encoding='utf-8',newline='') as f:
        w=csv.writer(f); w.writerow(['item_id','weight_kg','utility_points','mandatory'])
        for i in range(p.n): w.writerow([i+1,int(p.weight[i]),int(p.value[i]),int(i in p.mandatory)])
    with (out_dir/'conflicts.csv').open('w',encoding='utf-8',newline='') as f:
        w=csv.writer(f); w.writerow(['item_a','item_b'])
        for i,j in p.conflicts: w.writerow([i+1,j+1])
    with (out_dir/'instance.json').open('w',encoding='utf-8') as f:
        json.dump({'source':'synthetic; generated by create_problem','data_seed':DATA_SEED,
                   'capacity_kg':p.capacity,'mandatory':[i+1 for i in p.mandatory],
                   'conflicts':[[i+1,j+1] for i,j in p.conflicts],
                   'objects':p.n},f,ensure_ascii=False,indent=2)


def raw_value(x: np.ndarray, p: Problem) -> int:
    return int(np.dot(x, p.value))


def used_weight(x: np.ndarray, p: Problem) -> int:
    return int(np.dot(x, p.weight))


def violation(x: np.ndarray, p: Problem) -> tuple[int,int,int]:
    missing = sum(1 for i in p.mandatory if not x[i])
    conflicts = sum(1 for i,j in p.conflicts if x[i] and x[j])
    excess = max(0, used_weight(x,p)-p.capacity)
    return missing,conflicts,excess


def feasible(x: np.ndarray, p: Problem) -> bool:
    return violation(x,p) == (0,0,0)


def repair(x: np.ndarray, p: Problem) -> np.ndarray:
    """Гарантированный ремонт: обязательные -> конфликты -> вес.

    Для ограничений по парам удаляется необязательный элемент с меньшей
    полезностью/кг (детерминированное правило), для веса - худший по той
    же метрике необязательный элемент. Фитнес не вычисляется в ремонте.
    """
    y = np.asarray(x,dtype=np.bool_).copy()
    y[list(p.mandatory)] = True
    mandatory = set(p.mandatory)
    for a,b in p.conflicts:
        if not (y[a] and y[b]): continue
        if a in mandatory: drop=b
        elif b in mandatory: drop=a
        else:
            ra,rb = p.value[a]/p.weight[a],p.value[b]/p.weight[b]
            drop = a if (ra,a) < (rb,b) else b
        y[drop] = False
    # Удаление не создаёт новых конфликтов.
    while used_weight(y,p) > p.capacity:
        removable = [i for i in range(p.n) if y[i] and i not in mandatory]
        if not removable: raise ValueError('Обязательные предметы тяжелее вместимости')
        drop = min(removable,key=lambda i:(p.value[i]/p.weight[i],i))
        y[drop] = False
    assert feasible(y,p)
    return y


def greedy(p: Problem) -> np.ndarray:
    x = np.zeros(p.n,dtype=np.bool_); x[list(p.mandatory)]=True
    order=sorted((i for i in range(p.n) if i not in p.mandatory),
                 key=lambda i:(-p.value[i]/p.weight[i],i))
    for i in order:
        x[i]=True
        if not feasible(x,p):x[i]=False
    return x


def tournament(score: np.ndarray,rng:np.random.Generator,k:int=3) -> int:
    ids=rng.integers(0,len(score),size=k)
    return int(ids[np.argmax(score[ids])])


def crossover(a:np.ndarray,b:np.ndarray,rng:np.random.Generator,p_cross:float) -> tuple[np.ndarray,np.ndarray]:
    if rng.random()>=p_cross: return a.copy(),b.copy()
    mask=rng.random(len(a))<.5
    return np.where(mask,a,b).copy(),np.where(mask,b,a).copy()


def mutate(x: np.ndarray,rng:np.random.Generator,mode:str,p_gene:float) -> np.ndarray:
    y=x.copy()
    if mode=='bitflip':
        mask=rng.random(len(y))<p_gene
        y[mask]=~y[mask]
    elif mode=='swap':
        if rng.random()<min(1.0,p_gene*len(y)):
            i,j=rng.choice(len(y),size=2,replace=False)
            y[i],y[j]=y[j],y[i]
    else:raise ValueError(mode)
    return y


def penalty_score(x:np.ndarray,p:Problem) -> float:
    missing,conflicts,excess=violation(x,p)
    # Строгие ограничения оцениваются штрафами; они НЕ гарантируют допустимость.
    return raw_value(x,p) - 400.0*missing - 250.0*conflicts - 25.0*excess


@dataclass(frozen=True)
class Config:
    population: int=48
    generations: int=120
    elite: int=2
    crossover_probability: float=.88
    mutation_probability:float=1/40
    tournament_k:int=3

    @property
    def budget(self)->int:
        return self.population + (self.generations-1)*(self.population-self.elite)


def run_ga(p:Problem, seed:int, constraints:str, mutation:str,
           cfg:Config=Config()) -> dict:
    rng=np.random.default_rng(seed)
    n,mu=p.n,cfg.population
    pop=rng.random((mu,n)) < .32
    if constraints=='repair':
        pop=np.array([repair(x,p) for x in pop],dtype=np.bool_)
    fitness=np.zeros(mu,dtype=float)
    best=-np.inf;best_x=np.zeros(n,dtype=bool)
    eval_count=0;feasible_evals=0
    first_feasible_at=None
    best_trajectory=[]
    feasible_fraction_trajectory=[]
    start=time.perf_counter()

    def evaluate(index:int,x:np.ndarray) -> None:
        nonlocal eval_count, feasible_evals,best,best_x,first_feasible_at
        missing, conflicts, excess = violation(x,p)
        valid = (missing,conflicts,excess)==(0,0,0)
        # Фактическая целевая функция рассчитывается ровно ОДИН раз на особь.
        raw = raw_value(x,p)
        eval_count+=1
        if valid:
            feasible_evals+=1
            if first_feasible_at is None: first_feasible_at=eval_count
            if raw>best:
                best=raw;best_x=x.copy()
        fitness[index] = (raw if constraints=='repair' else
                          raw - 400.0*missing - 250.0*conflicts - 25.0*excess)

    for i in range(mu):evaluate(i,pop[i])
    best_trajectory.append(float(best) if np.isfinite(best) else np.nan)
    feasible_fraction_trajectory.append(feasible_evals/eval_count)

    for gen in range(1,cfg.generations):
        elite_ids=np.argsort(-fitness,kind='stable')[:cfg.elite]
        elites=pop[elite_ids].copy()
        elite_scores=fitness[elite_ids].copy()
        children=[]
        while len(children) < (mu-cfg.elite):
            a=pop[tournament(fitness,rng,cfg.tournament_k)]
            b=pop[tournament(fitness,rng,cfg.tournament_k)]
            ca,cb=crossover(a,b,rng,cfg.crossover_probability)
            for child in (ca,cb):
                child=mutate(child,rng,mutation,cfg.mutation_probability)
                if constraints=='repair':child=repair(child,p)
                children.append(child)
                if len(children)==mu-cfg.elite:break
        pop=np.vstack([elites,np.array(children,dtype=np.bool_)])
        fitness[:cfg.elite]=elite_scores
        for i in range(cfg.elite,mu):evaluate(i,pop[i])
        best_trajectory.append(float(best) if np.isfinite(best) else np.nan)
        feasible_fraction_trajectory.append(feasible_evals/eval_count)
    assert eval_count==cfg.budget
    if np.isfinite(best):assert feasible(best_x,p)
    return {'seed':int(seed),'algorithm':'GA','constraints':constraints,'mutation':mutation,
            'best':int(best) if np.isfinite(best) else None,
            'solution':np.flatnonzero(best_x).astype(int).tolist() if np.isfinite(best) else [],
            'weight':used_weight(best_x,p) if np.isfinite(best) else None,
            'evaluations':eval_count,'feasible_evaluations':feasible_evals,
            'feasible_rate':feasible_evals/eval_count,'first_feasible_eval':first_feasible_at,
            'trajectory':best_trajectory,'valid_trajectory':feasible_fraction_trajectory,
            'elapsed_seconds':time.perf_counter()-start}


def run_random(p:Problem,seed:int,cfg:Config=Config()) -> dict:
    rng=np.random.default_rng(seed)
    best=-np.inf;best_x=np.zeros(p.n,dtype=bool)
    trajectory=[];feasible_fraction=[]
    start=time.perf_counter()
    evals=0
    for gen in range(cfg.generations):
        batch=cfg.population if gen==0 else cfg.population-cfg.elite
        for _ in range(batch):
            x=repair(rng.random(p.n)<.32,p)
            v=raw_value(x,p)
            evals+=1
            if v>best:best=v;best_x=x.copy()
        trajectory.append(float(best));feasible_fraction.append(1.0)
    assert evals==cfg.budget
    return {'seed':int(seed),'algorithm':'random_feasible','constraints':'repair','mutation':'none',
            'best':int(best),'solution':np.flatnonzero(best_x).astype(int).tolist(),
            'weight':used_weight(best_x,p),'evaluations':evals,
            'feasible_evaluations':evals,'feasible_rate':1.0,'first_feasible_eval':1,
            'trajectory':trajectory,'valid_trajectory':feasible_fraction,
            'elapsed_seconds':time.perf_counter()-start}


def stat(runs:list[dict])->dict:
    vals=np.array([x['best'] for x in runs],dtype=float)
    vals=vals[np.isfinite(vals)]
    if len(vals)==0:return {}
    return {'best':int(np.max(vals)),'mean':float(vals.mean()),'median':float(np.median(vals)),
            'std_sample':float(vals.std(ddof=1)),'worst':int(np.min(vals)),
            'mean_feasible_rate':float(np.mean([x['feasible_rate'] for x in runs])),
            'mean_elapsed_seconds':float(np.mean([x['elapsed_seconds'] for x in runs])),
            'success_feasible_runs':int(sum(x['best'] is not None for x in runs))}


def plot_results(groups:dict[str,list[dict]],out_dir:Path)->None:
    plt.rcParams.update({'font.size':10,'font.family':'DejaVu Sans'})
    fig,ax=plt.subplots(figsize=(9,5))
    for name,runs in groups.items():
        data=np.array([r['trajectory'] for r in runs],dtype=float)
        ax.plot(np.arange(data.shape[1]),np.nanmean(data,axis=0),label=name)
    ax.set(xlabel='Поколение / эквивалентная партия оценок',
           ylabel='Среднее лучшее допустимое значение',title='Сходимость: 20 независимых запусков на конфигурацию')
    ax.grid(alpha=.2);ax.legend(loc='lower right');fig.tight_layout();fig.savefig(out_dir/'convergence.png',dpi=180);plt.close(fig)

    fig,ax=plt.subplots(figsize=(9,5))
    series=[[r['best'] for r in runs if r['best'] is not None] for runs in groups.values()]
    ax.boxplot(series, tick_labels=list(groups),showmeans=True)
    ax.set(ylabel='Лучшее допустимое значение за запуск',title='Распределение результатов 20 независимых запусков')
    ax.tick_params(axis='x',labelrotation=10)
    ax.grid(alpha=.2,axis='y');fig.tight_layout();fig.savefig(out_dir/'boxplot.png',dpi=180);plt.close(fig)

    fig,ax=plt.subplots(figsize=(9,5))
    labels=list(groups)
    rates=[np.mean([r['feasible_rate'] for r in runs]) for runs in groups.values()]
    ax.bar(labels, rates)
    ax.set(ylim=(0,1.04),ylabel='Доля допустимых оценённых кандидатов',
           title='Обработка ограничений: доля допустимых кандидатов')
    ax.tick_params(axis='x',labelrotation=10)
    for i,v in enumerate(rates):ax.text(i,v+.016,f'{v:.3f}',ha='center')
    fig.tight_layout();fig.savefig(out_dir/'feasible_rate.png',dpi=180);plt.close(fig)

    fig,ax=plt.subplots(figsize=(7,7));ax.set_xlim(0,1);ax.set_ylim(0,1);ax.axis('off')
    steps=[('Генерация бинарной популяции',.91),('Проверка / ремонт или штраф',.77),
           ('Оценка фитнеса',.63),('Турнир + равномерный кроссовер',.49),
           ('Мутация: bitflip или swap',.35),('Элитизм и новое поколение',.21),
           ('Останов и best допустимое',.07)]
    for label,y in steps:ax.text(.5,y,label,ha='center',va='center',bbox=dict(boxstyle='round,pad=.50',edgecolor='#35557b',facecolor='#f1f5fa'))
    for (_,y),(_,y2) in zip(steps,steps[1:]):
        ax.annotate('',xy=(.5,y2+.039),xytext=(.5,y-.039),arrowprops=dict(arrowstyle='->'))
    ax.annotate('повтор',xy=(.30,.65),xytext=(.17,.19),arrowprops=dict(arrowstyle='->',connectionstyle='arc3,rad=-.25'))
    fig.tight_layout();fig.savefig(out_dir/'flowchart.png',dpi=190);plt.close(fig)


def demonstrate(p:Problem)->list[dict]:
    all_zero=np.zeros(p.n,dtype=bool)
    mandatory=np.zeros(p.n,dtype=bool);mandatory[list(p.mandatory)]=True
    greedy_solution=greedy(p)
    missing=mandatory.copy();missing[p.mandatory[0]]=False
    a,b=next((a,b) for a,b in p.conflicts if not(a in p.mandatory and b in p.mandatory))
    conflict=mandatory.copy();conflict[a]=True;conflict[b]=True
    overweight=np.ones(p.n,dtype=bool)
    return [dict(kind=name,items=[int(i+1) for i in np.flatnonzero(x)],
                 value=raw_value(x,p),weight=used_weight(x,p),
                 feasible=feasible(x,p),violation=violation(x,p))
            for name,x in [('допустимый: только обязательные',mandatory),
                           ('допустимый: жадная эвристика',greedy_solution),
                           ('недопустимый: нет обязательного',missing),
                           ('недопустимый: конфликт',conflict),
                           ('недопустимый: перегруз и конфликты',overweight)]]


def experiment(out_dir:Path,runs:int=20,seed_base:int=DEFAULT_SEED_BASE,cfg:Config=Config())->dict:
    if runs<20: raise ValueError('Методичка требует >=20 независимых запусков')
    out_dir.mkdir(parents=True,exist_ok=True)
    p=create_problem();save_problem(p,out_dir)
    plans=[('ГА: ремонт / bitflip','repair','bitflip'),
           ('ГА: штраф / bitflip','penalty','bitflip'),
           ('ГА: ремонт / swap','repair','swap')]
    groups={}
    for name,c,m in plans:
        groups[name]=[run_ga(p,seed_base+i,c,m,cfg) for i in range(runs)]
    groups['Случайный допустимый']= [run_random(p,seed_base+i,cfg) for i in range(runs)]
    flat=[(name,r) for name,gg in groups.items() for r in gg]
    with (out_dir/'runs.csv').open('w',encoding='utf-8',newline='') as f:
        w=csv.writer(f);w.writerow(['configuration','seed','best_feasible_utility','weight_kg',
                                    'evaluations','feasible_evaluations','feasible_rate',
                                    'first_feasible_evaluation','elapsed_seconds','item_ids'])
        for name,r in flat:
            w.writerow([name,r['seed'],r['best'],r['weight'],r['evaluations'],
                        r['feasible_evaluations'],f"{r['feasible_rate']:.12g}",
                        r['first_feasible_eval'],f"{r['elapsed_seconds']:.9g}",
                        ' '.join(str(i+1) for i in r['solution'])])
    with (out_dir/'trajectories.csv').open('w',encoding='utf-8',newline='') as f:
        w=csv.writer(f);w.writerow(['configuration','seed','generation','best_feasible_utility_so_far',
                                    'cumulative_feasible_fraction'])
        for name,r in flat:
            for g,(v,rate) in enumerate(zip(r['trajectory'],r['valid_trajectory'])):
                w.writerow([name,r['seed'],g,v,f'{rate:.10f}'])
    best_name,best_result=max(flat,key=lambda nr:nr[1]['best'] if nr[1]['best'] is not None else -1)
    best_solution=np.zeros(p.n,dtype=bool);best_solution[best_result['solution']]=True
    greedy_x=greedy(p)
    summary={'variant':'демонстрационный V=3; N,Q отсутствуют','lab1_dimension_note':'d=5+(22 mod 6)=9 относится только к ЛР1',
             'n':p.n,'mandatory_1based':[i+1 for i in p.mandatory],
             'capacity':p.capacity,'conflicts_1based':[[i+1,j+1] for i,j in p.conflicts],
             'data_seed':DATA_SEED,'run_seed_base':seed_base,'runs_per_group':runs,
             'budget_per_run':cfg.budget,
             'parameters':{'population':cfg.population,'generations':cfg.generations,
                           'elitism':cfg.elite,'tournament_k':cfg.tournament_k,
                           'crossover_probability':cfg.crossover_probability,
                           'mutation_probability_per_bit':cfg.mutation_probability,
                           'initial_1_probability':.32,'crossover':'uniform',
                           'penalty_missing':400,'penalty_conflict':250,'penalty_excess_kg':25},
             'statistics':{name:stat(gg) for name,gg in groups.items()},
             'best_overall':{'configuration':best_name,'seed':best_result['seed'],
                             'value':best_result['best'],'weight':best_result['weight'],
                             'items_1based':[i+1 for i in best_result['solution']],
                             'checks':list(violation(best_solution,p))},
             'greedy':{'value':raw_value(greedy_x,p),'weight':used_weight(greedy_x,p),
                       'items_1based':[int(i+1) for i in np.flatnonzero(greedy_x)]},
             'examples':demonstrate(p)}
    with (out_dir/'summary.json').open('w',encoding='utf-8') as f:
        json.dump(summary,f,ensure_ascii=False,indent=2)
    with (out_dir/'config.json').open('w',encoding='utf-8') as f:
        json.dump({'runs':runs,'seed_base':seed_base,'data_seed':DATA_SEED,
                   **summary['parameters'],'evaluation_budget':cfg.budget},f,ensure_ascii=False,indent=2)
    with (out_dir/'best_solution.csv').open('w',encoding='utf-8',newline='') as f:
        w=csv.writer(f);w.writerow(['item_id','weight_kg','utility_points','mandatory'])
        for i in best_result['solution']:w.writerow([i+1,int(p.weight[i]),int(p.value[i]),int(i in p.mandatory)])
    plot_results(groups,out_dir)
    return summary


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,default=Path('results'))
    parser.add_argument('--runs',type=int,default=20)
    parser.add_argument('--seed-base',type=int,default=DEFAULT_SEED_BASE)
    args=parser.parse_args()
    s=experiment(args.out,args.runs,args.seed_base)
    print(json.dumps({'statistics':s['statistics'],'best_overall':s['best_overall'],
                      'greedy':s['greedy'],'budget_per_run':s['budget_per_run']},ensure_ascii=False,indent=2))


if __name__=='__main__':main()
